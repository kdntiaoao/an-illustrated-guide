def add(a: str, b: str) -> float:
    """Add two numbers."""
    return float(a) + float(b)


def subtract(a: str, b: str) -> float:
    """Subtract two numbers."""
    return float(a) - float(b)


def multiply(a: str, b: str) -> float:
    """Multiply two numbers."""
    return float(a) * float(b)
